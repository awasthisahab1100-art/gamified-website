        document.addEventListener('DOMContentLoaded', function() {
            // Load saved language preference
            const savedLanguage = localStorage.getItem('preferred-language');
            if (savedLanguage && translations[savedLanguage]) {
                changeLanguage(savedLanguage);
            }

            // Check if student is logged in
            if (currentStudent) {
                showStudentLoggedInState();
            }

            // Check if teacher is logged in
            if (currentTeacher) {
                showTeacherLoggedInState();
            }

            startAutoPlay();
            
            // Mobile menu toggle
            const mobileToggle = document.getElementById('mobile-toggle');
            const navMenu = document.getElementById('nav-menu');
            
            mobileToggle?.addEventListener('click', () => {
                navMenu.classList.toggle('active');
            });

            // Auto-play testimonials
            setInterval(() => {
                testimonialIndex = (testimonialIndex + 1) % 2;
                showTestimonial(testimonialIndex);
            }, 4000);

            // Add click handlers for slider controls
            document.querySelectorAll('.slider-btn').forEach((btn, index) => {
                btn.addEventListener('click', () => showTestimonial(index));
            });

            // Intersection Observer for animations
            const observer = new IntersectionObserver((entries) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting) {
                        entry.target.style.animation = 'fadeInUp 0.8s ease forwards';
                        if (entry.target.classList.contains('stats-container')) {
                            animateCounters();
                        }
                    }
                });
            }, {
                threshold: 0.1,
                rootMargin: '0px 0px -50px 0px'
            });

            // Observe elements for animations
            const animatedElements = document.querySelectorAll('.stat-item, .course-card, .feature-item');
            animatedElements.forEach(el => observer.observe(el));

            // Smooth scrolling for navigation links
            document.querySelectorAll('a[href^="#"]').forEach(anchor => {
                anchor.addEventListener('click', function (e) {
                    e.preventDefault();
                    const target = document.querySelector(this.getAttribute('href'));
                    if (target) {
                        target.scrollIntoView({
                            behavior: 'smooth',
                            block: 'start'
                        });
                    }
                });
            });
        });