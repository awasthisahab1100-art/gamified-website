        function showChapters(classNumber, subjectName) {
            currentSubject = subjectName;
            
            const chaptersSection = document.getElementById('chapters-section');
            const chaptersList = document.getElementById('chapters-list');
            
            chaptersSection.style.display = 'block';
            chaptersList.innerHTML = '';
            
            const backBtn = document.createElement('button');
            backBtn.className = 'back-btn';
            backBtn.onclick = () => hideChapters();
            backBtn.innerHTML = '<i class="fas fa-arrow-left"></i> Back to Subjects';
            chaptersList.appendChild(backBtn);
            
            const chapters = chaptersData[subjectName] && chaptersData[subjectName][classNumber] 
                ? chaptersData[subjectName][classNumber] 
                : [`Chapter 1: Introduction to ${subjectName}`, `Chapter 2: Basic Concepts`, `Chapter 3: Advanced Topics`];
            
            chapters.forEach((chapter, index) => {
                const chapterItem = document.createElement('div');
                chapterItem.className = 'chapter-item';
                chapterItem.onclick = () => startChapter(chapter);
                chapterItem.innerHTML = `
                    <div class="chapter-number">${index + 1}</div>
                    <div class="chapter-title">${chapter}</div>
                    <i class="fas fa-play-circle" style="font-size: 1.2rem; opacity: 0.7;"></i>
                `;
                chaptersList.appendChild(chapterItem);
            });
            
            chaptersSection.scrollIntoView({ behavior: 'smooth' });
        }

