            let correctCount = 0;
            let incorrectCount = 0;
            
            currentQuiz.questions_data.forEach((question, index) => {
                if (quizAnswers[index] === question.correct) {
                    correctCount++;
                } else if (quizAnswers[index] !== null) {
                    incorrectCount++;
                }
            });
            
            const totalQuestions = currentQuiz.questions_data.length;
            const unanswered = totalQuestions - correctCount - incorrectCount;
            const scorePercentage = Math.round((correctCount / totalQuestions) * 100);
            
            const timeTaken = Math.floor((Date.now() - quizStartTime) / 1000);
            const timeTakenMinutes = Math.floor(timeTaken / 60);
            const timeTakenSeconds = timeTaken % 60;
            
            // Show results
            document.getElementById('quizTakingModal').style.display = 'none';
            document.getElementById('quizResultModal').style.display = 'block';
            
            // Update result display
            const scoreElement = document.getElementById('quizResultScore');
