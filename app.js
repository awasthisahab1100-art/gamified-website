        function startLiveChatSimulation() {
            const chatMessages = [
                { author: 'Teacher', message: 'Let\'s start with today\'s topic!', time: getCurrentTime() },
                { author: 'Rahul', message: 'Sir, can you explain the formula again?', time: getCurrentTime() },
                { author: 'Priya', message: 'This is very helpful, thank you!', time: getCurrentTime() },
                {author: 'Teacher', message: 'Great question, Rahul. Let me demonstrate.', time: getCurrentTime() },
                { author: 'Ankit', message: 'I have a doubt about the previous example', time: getCurrentTime() },
                { author: 'Sneha', message: 'Crystal clear explanation sir!', time: getCurrentTime() }
            ];
            
            let messageIndex = 0;
            chatSimulationInterval = setInterval(() => {
                if (messageIndex < chatMessages.length) {
                    addChatMessage(chatMessages[messageIndex]);
                    messageIndex++;
                } else {
                    // Reset and continue with new messages
                    messageIndex = 0;
                }
            }, 8000);
        }

