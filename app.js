        function generateSampleChapters(subject, studentClass) {
            // Get chapters for the subject and class, or generate sample ones
            const subjectChapters = chaptersData[subject] && chaptersData[subject][studentClass] 
                ? chaptersData[subject][studentClass]
                : [`Chapter 1: Introduction to ${subject}`, `Chapter 2: Basic Concepts`, `Chapter 3: Advanced Topics`];
            
            return subjectChapters.slice(0, 8).map((chapter, index) => {
                // Simulate different completion statuses
                let status, score;
                if (index < 4) {
                    status = 'completed';
                    score = `${85 + Math.floor(Math.random() * 15)}/100`;
                } else if (index < 6) {
                    status = 'in-progress';
                    score = '';
                } else {
                    status = 'not-started';
                    score = '';
                }
                
                return {
                    name: chapter,
                    status: status,
                    score: score
                };
            });
        }

