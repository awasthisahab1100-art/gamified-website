        function generateQuestion() {
            const operations = ['+', '-', '×', '÷'];
            const operation = operations[Math.floor(Math.random() * operations.length)];
            
            let num1, num2, answer;
            
            // Adjust difficulty based on level
            const maxNum = Math.min(10 + (gameLevel * 5), 100);
            
            switch (operation) {
                case '+':
                    num1 = Math.floor(Math.random() * maxNum) + 1;
                    num2 = Math.floor(Math.random() * maxNum) + 1;
                    answer = num1 + num2;
                    break;
                case '-':
                    num1 = Math.floor(Math.random() * maxNum) + Math.floor(maxNum / 2);
                    num2 = Math.floor(Math.random() * (num1 - 1)) + 1;
                    answer = num1 - num2;
                    break;
                case '×':
                    num1 = Math.floor(Math.random() * Math.min(12, maxNum)) + 1;
                    num2 = Math.floor(Math.random() * Math.min(12, maxNum)) + 1;
                    answer = num1 * num2;
                    break;
                case '÷':
                    answer = Math.floor(Math.random() * Math.min(12, maxNum)) + 1;
                    num2 = Math.floor(Math.random() * Math.min(12, maxNum)) + 1;
                    num1 = answer * num2;
                    break;
            }
            
            currentQuestion = {
                question: `${num1} ${operation} ${num2} = ?`,
                answer: answer
            };
            
            document.getElementById('mathQuestion').textContent = currentQuestion.question;
            document.getElementById('answerInput').value = '';
            document.getElementById('answerInput').focus();
        }

